def _lang():
    try:
        code = (get_workbench().get_option("general.language") or "en").lower()
    except Exception:
        code = "en"
    return code[:2] if code[:2] in _STRINGS else "en"


def t(key, **kw):
    text = _STRINGS[_lang()].get(key) or _STRINGS["en"].get(key, key)
    return text.format(**kw) if kw else text
